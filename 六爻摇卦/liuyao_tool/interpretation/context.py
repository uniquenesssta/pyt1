"""透明的主题词匹配；不声称理解未提供的情节或对方心理。"""
from dataclasses import dataclass


@dataclass(frozen=True)
class Topic:
    name: str
    keywords: tuple[str, ...]
    focus: str
    check: str


TOPICS = (
    Topic("工作与项目", ("工作", "事业", "项目", "职业", "辞职", "跳槽", "设计", "客户", "订单", "生意", "开店"),
          "目标、进度、能力与实际支持之间的关系", "目前最关键的推进条件是什么？怎样通过一个小步骤核实它？"),
    Topic("合作与资源", ("合作", "合伙", "合同", "分工", "资源", "预算", "钱", "收益", "回款", "投资", "股票"),
          "双方约定、资源承接与各自可以承担的范围", "哪些约定已有事实依据，哪些仍只是期待？需要核对哪些条件？"),
    Topic("关系与沟通", ("感情", "恋爱", "对象", "伴侣", "结婚", "分手", "复合", "家庭", "朋友", "沟通", "关系"),
          "双方真实表达、互动方式与边界", "哪些信息来自对方明确表达，哪些只是自己的推测？还有什么可以直接沟通？"),
    Topic("学习与成长", ("学习", "考试", "考研", "考证", "学校", "课程", "练习", "技能", "成长"),
          "当前基础、练习方式与反馈", "能否用一次具体练习或反馈，分清已经掌握和仍需补足的部分？"),
    Topic("选择与变化", ("选择", "决定", "要不要", "是否", "换", "搬家", "出行", "旅行", "改变", "离开"),
          "选择条件、可逆程度与需要补充的信息", "不同选择各需要什么条件？哪些信息补齐后会改变你的判断？"),
)
GENERAL = Topic("综合阅读", (), "当前条件、互动方式与下一步可观察的变化",
                "目前掌握了哪些事实？还有哪个关键条件需要进一步确认？")


def match_topics(question, background):
    # 问题优先；背景只在问题未命中时用于辅助识别。
    for text in (question.strip(), background.strip()):
        matches = tuple(topic for topic in TOPICS if any(word in text for word in topic.keywords))
        if matches:
            return matches
    return (GENERAL,)
